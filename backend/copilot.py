"""EduRadar Copilot: database facts + guideline retrieval (demo-safe by default)."""
from __future__ import annotations

import os
import re
from datetime import date, timedelta
from pathlib import Path

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field
from sqlalchemy import select, func
from sqlalchemy.orm import Session
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

from .db import Student, Intervention, session_dep

router = APIRouter(prefix="/api/copilot", tags=["Copilot"])
DOC_FILE = Path(__file__).resolve().parent.parent / "knowledge" / "demo_support_guidelines.md"

class AskIn(BaseModel):
    question: str = Field(min_length=3, max_length=500)


def docs():
    text = DOC_FILE.read_text(encoding="utf-8")
    sections = [s.strip() for s in re.split(r"(?=^## )", text, flags=re.M) if s.strip()]
    return [(f"guide-{i+1}", section) for i, section in enumerate(sections)]


def retrieve(question: str, k=2):
    entries = docs()
    texts = [x[1] for x in entries]
    vec = TfidfVectorizer(ngram_range=(1, 2), stop_words="english").fit_transform(texts + [question])
    similarities = cosine_similarity(vec[-1], vec[:-1])[0]
    choices = sorted(range(len(texts)), key=lambda i: similarities[i], reverse=True)
    return [{"id": entries[i][0], "excerpt": texts[i][:1100], "similarity": round(float(similarities[i]), 3)}
            for i in choices[:k] if similarities[i] > 0.025]


def row(st):
    return {"student_id": st.student_id, "name": st.name, "priority": st.effective_priority,
            "attendance_alert": st.attendance_alert, "trend_warning": bool(st.trend_warning)}


def demo_filter(q):
    # Block uploaded student files by default; this is NOT a substitute for authentication.
    if os.getenv("EDURADAR_COPILOT_DEMO_ONLY", "1") == "1":
        q = q.where(Student.data_source.in_(["synthetic", "simulated-edge-case"]))
    return q


def guideline_answer(question, evidence):
    # Optional genuine LLM-based RAG for demo policy text only. Never send student records.
    key = os.getenv("OPENAI_API_KEY")
    if key and os.getenv("EDURADAR_COPILOT_USE_LLM", "0") == "1" and evidence:
        import httpx
        material = "\n\n".join(f"[{x['id']}] {x['excerpt']}" for x in evidence)
        prompt = ("Answer this question using ONLY the following demonstration guidance excerpts. "
                  "If they do not answer the question, explicitly say so. "
                  "Cite sources as [guide-N]. Never invent a school policy. "
                  "Guidance is illustrative and must be confirmed by teachers.\n\n" 
                  f"{material}\n\nQuestion: {question}")
        try:
            response = httpx.post("https://api.openai.com/v1/chat/completions",
                headers={"Authorization": f"Bearer {key}"},
                json={"model": os.getenv("EDURADAR_COPILOT_MODEL", "gpt-4.1-mini"),
                      "messages": [{"role": "system", "content": "You answer only from cited demo guidance."},
                                   {"role": "user", "content": prompt}], "temperature": 0.1,
                      "max_tokens": 350}, timeout=15)
            response.raise_for_status()
            return response.json()["choices"][0]["message"]["content"]
        except (httpx.HTTPError, KeyError, IndexError, ValueError):
            pass
    if not evidence:
        return "I couldn't find relevant guidance in the uploaded demonstration guide. Ask a teacher to review this question."
    return "Relevant demonstration guidance (not an official school policy):\n\n" + "\n\n".join(
        f"[{x['id']}] {x['excerpt'][:430]}" for x in evidence)


@router.post("/ask")
def ask(body: AskIn, s: Session = Depends(session_dep)):
    if os.getenv("EDURADAR_COPILOT_ENABLED", "0") != "1":
        raise HTTPException(503, "Copilot is disabled. Set EDURADAR_COPILOT_ENABLED=1 for synthetic-data demos.")
    q = body.question.strip()
    low = q.lower()
    sources = []
    records = []
    intent = "guideline"

    # Data questions use deterministic SQL, never text-to-SQL generated by an LLM.
    if re.search(r"\b(follow.?up|overdue|intervention|due tomorrow|due today)\b", low):
        intent = "followups"
        tomorrow = date.today() + timedelta(days=1)
        due = tomorrow if "tomorrow" in low else date.today()
        qry = select(Intervention, Student).join(Student, Intervention.student_id == Student.student_id).where(
            Intervention.status.in_(["Planned", "In progress"]))
        if "overdue" in low:
            qry = qry.where(Intervention.followup_date < date.today())
        else:
            qry = qry.where(Intervention.followup_date == due)
        qry = demo_filter(qry).order_by(Intervention.followup_date, Intervention.id).limit(21)
        matches = s.execute(qry).all()
        records = [{"student_id": st.student_id, "name": st.name, "action": iv.action[:180],
                    "followup_date": iv.followup_date.isoformat(), "status": iv.status} for iv, st in matches[:20]]
        label = "overdue" if "overdue" in low else f"due {due.isoformat()} (server date)"
        answer = f"Found {len(records)} demonstration follow-ups {label}." + (
            " Showing the first 20; refine your request for more." if len(matches) > 20 else "")
        sources = [{"id": "db-interventions", "excerpt": "Live SQLite interventions joined to students"}]
    elif re.search(r"\b(declin\w*|falling|low attendance|attendance alert|high priority|unreviewed|need(s)? review|without review)\b", low):
        intent = "student_search"
        qry = select(Student)
        if "attendance" in low:
            qry = qry.where(Student.attendance_alert.in_(["Declining attendance", "Low and declining"])
                            if ("declin" in low or "falling" in low) else
                            Student.attendance_alert.in_(["Low attendance", "Low and declining"]))
        elif "declin" in low or "falling" in low:
            qry = qry.where(Student.trend_warning.is_(True))
        elif "high" in low:
            qry = qry.where(Student.effective_priority == "High")
        if "unreviewed" in low or "without review" in low or "need" in low:
            qry = qry.where(Student.reviewed.is_(False))
        qry = demo_filter(qry)
        total = s.scalar(select(func.count()).select_from(qry.subquery())) or 0
        found = s.execute(qry.order_by(Student.student_id).limit(20)).scalars().all()
        records = [row(st) for st in found]
        answer = f"Found {total} matching demonstration students. Showing up to 20 records."
        sources = [{"id": "db-students", "excerpt": "Live SQLite student priority, attendance and review columns"}]
    else:
        # Individual ID lookup, with only synthetic records allowed.
        sid = re.search(r"\b(?:S\d{5}|SIM-E\d{2})\b", q, re.I)
        if sid:
            intent = "student_profile"
            st = s.get(Student, sid.group(0).upper())
            if st and (os.getenv("EDURADAR_COPILOT_DEMO_ONLY", "1") != "1" or st.data_source in ("synthetic", "simulated-edge-case")):
                records = [row(st)]
                answer = (f"{st.student_id} has model priority {st.model_priority or 'not available'} and "
                          f"effective teacher-reviewed priority {st.effective_priority or 'not available'}. "
                          "These are synthetic indicators, not a judgment about the student.")
                sources = [{"id": "db-students", "excerpt": "Live SQLite student record; original and effective priority are separate"}]
            else:
                answer = "No authorized demonstration record found for that student ID."
        else:
            evidence = retrieve(q)
            answer = guideline_answer(q, evidence)
            sources = evidence

    return {"answer": answer, "intent": intent, "records": records, "sources": sources,
            "disclaimer": "Synthetic demonstration only. Teachers must verify records and approve support actions. No causal claims."}
